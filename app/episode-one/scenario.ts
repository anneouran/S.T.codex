export type EpisodeFrame = {
  kind: "narration" | "speech" | "protagonist" | "location";
  name?: string;
  text: string;
  background: string;
  portrait?: string;
  darken: boolean;
  pan: boolean;
  reversePan: boolean;
};

// 改行を一つの表示単位にし、立ち絵は明示的な消去・差し替えまで保持する。
export function parseManuscript(source: string): EpisodeFrame[] {
  const frames: EpisodeFrame[] = [];
  let background = "黒";
  let portrait: string | undefined;
  let kind: EpisodeFrame["kind"] = "narration";
  let name: string | undefined;
  let darken = false;
  let pan = false;
  let reversePan = false;
  for (const line of source.split("\n")) {
    if (!line) continue;
    if (line.startsWith("効果：")) {
      if (line.includes("暗転")) darken = true;
      if (line.includes("左から右")) reversePan = true;
      if (line.includes("背景移動")) pan = true;
      if (line.includes("立ち絵") && line.includes("消える")) portrait = undefined;
      continue;
    }
    if (line.startsWith("背景：")) { background = line.slice(3); continue; }
    if (line.startsWith("立ち絵：")) { portrait = line.slice(4); continue; }
    if (line.startsWith("場所表示：")) {
      frames.push({ kind: "location", text: line.slice(5), background, portrait, darken, pan, reversePan });
      darken = pan = reversePan = false;
      continue;
    }
    const heading = /^(セリフ|主人公|ナレーション)：(.*)$/.exec(line);
    if (heading) {
      kind = heading[1] === "セリフ" ? "speech" : heading[1] === "主人公" ? "protagonist" : "narration";
      name = heading[2] || undefined;
      continue;
    }
    frames.push({ kind, name, text: line, background, portrait, darken, pan, reversePan });
    darken = pan = reversePan = false;
  }
  return frames;
}

export const frames = parseManuscript(manuscript);
